export function seedInternshipsData(query) {
  try {
    const existing = query.get('SELECT count(*) as count FROM internships');
    if (existing && existing.count >= 10) {
      return;
    }

    for (const item of SEED_INTERNSHIPS) {
      query.run(`
        INSERT INTO internships (
          id, title, company, company_logo_url, role, category, location, mode,
          stipend, stipend_amount, duration, skills_required, eligibility,
          eligible_branches, eligible_years, deadline, apply_url, source_platform,
          last_verified_at, verification_status, description, responsibilities,
          qualifications, selection_process, is_active
        ) VALUES (
          ?, ?, ?, ?, ?, ?, ?, ?,
          ?, ?, ?, ?, ?,
          ?, ?, ?, ?, ?,
          ?, ?, ?, ?,
          ?, ?, 1
        )
        ON CONFLICT(id) DO UPDATE SET
          title = excluded.title,
          company = excluded.company,
          company_logo_url = excluded.company_logo_url,
          role = excluded.role,
          category = excluded.category,
          location = excluded.location,
          mode = excluded.mode,
          stipend = excluded.stipend,
          stipend_amount = excluded.stipend_amount,
          duration = excluded.duration,
          skills_required = excluded.skills_required,
          eligibility = excluded.eligibility,
          eligible_branches = excluded.eligible_branches,
          eligible_years = excluded.eligible_years,
          deadline = excluded.deadline,
          apply_url = excluded.apply_url,
          source_platform = excluded.source_platform,
          last_verified_at = excluded.last_verified_at,
          verification_status = excluded.verification_status,
          description = excluded.description,
          responsibilities = excluded.responsibilities,
          qualifications = excluded.qualifications,
          selection_process = excluded.selection_process,
          is_active = 1
      `, [
        item.id, item.title, item.company, item.company_logo_url, item.role, item.category, item.location, item.mode,
        item.stipend, item.stipend_amount, item.duration, item.skills_required, item.eligibility,
        item.eligible_branches, item.eligible_years, item.deadline, item.apply_url, item.source_platform,
        item.last_verified_at, item.verification_status, item.description, item.responsibilities,
        item.qualifications, item.selection_process
      ]);
    }
    console.log(`✓ Seeded ${SEED_INTERNSHIPS.length} verified authentic internships into database.`);
  } catch (err) {
    console.warn('Notice seeding internships:', err.message);
  }
}
