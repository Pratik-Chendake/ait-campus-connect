export function seedScholarshipsData(db) {
  const insertScholarship = db.prepare(`
    INSERT INTO scholarships (
      slug, title, name, provider, amount, eligibility, deadline, category, subcategory, academic_year,
      description, benefits_summary, amount_min, amount_max, amount_display,
      education_level, eligible_branches, eligible_years, min_percentage, max_income,
      applicable_states, outside_state_study_allowed, gender_restriction,
      category_restriction, defence_category, application_type,
      application_open_at, application_close_at, institute_verification_deadline,
      official_application_url, apply_url, official_scheme_url, official_guideline_url,
      who_can_apply, who_cannot_apply, required_documents, application_procedure,
      status, verification_status, last_verified_at, is_featured, is_active
    ) VALUES (
      ?, ?, ?, ?, ?, ?, ?, ?, ?, ?,
      ?, ?, ?, ?, ?,
      ?, ?, ?, ?, ?,
      ?, ?, ?,
      ?, ?, ?,
      ?, ?, ?,
      ?, ?, ?, ?,
      ?, ?, ?, ?,
      ?, ?, datetime('now'), ?, 1
    )
    ON CONFLICT(slug) DO UPDATE SET
      title = excluded.title,
      name = excluded.name,
      provider = excluded.provider,
      amount = excluded.amount,
      eligibility = excluded.eligibility,
      deadline = excluded.deadline,
      category = excluded.category,
      subcategory = excluded.subcategory,
      academic_year = excluded.academic_year,
      description = excluded.description,
      benefits_summary = excluded.benefits_summary,
      amount_min = excluded.amount_min,
      amount_max = excluded.amount_max,
      amount_display = excluded.amount_display,
      education_level = excluded.education_level,
      eligible_branches = excluded.eligible_branches,
      eligible_years = excluded.eligible_years,
      min_percentage = excluded.min_percentage,
      max_income = excluded.max_income,
      applicable_states = excluded.applicable_states,
      outside_state_study_allowed = excluded.outside_state_study_allowed,
      gender_restriction = excluded.gender_restriction,
      category_restriction = excluded.category_restriction,
      defence_category = excluded.defence_category,
      application_type = excluded.application_type,
      application_open_at = excluded.application_open_at,
      application_close_at = excluded.application_close_at,
      institute_verification_deadline = excluded.institute_verification_deadline,
      official_application_url = excluded.official_application_url,
      apply_url = excluded.apply_url,
      official_scheme_url = excluded.official_scheme_url,
      official_guideline_url = excluded.official_guideline_url,
      who_can_apply = excluded.who_can_apply,
      who_cannot_apply = excluded.who_cannot_apply,
      required_documents = excluded.required_documents,
      application_procedure = excluded.application_procedure,
      status = excluded.status,
      verification_status = excluded.verification_status,
      is_featured = excluded.is_featured,
      updated_at = datetime('now')
  `);

  const insertRule = db.prepare(`
    INSERT INTO scholarship_eligibility_rules (
      scholarship_id, criterion_type, operator, criterion_value, is_mandatory, explanation, source_reference
    ) VALUES (?, ?, ?, ?, ?, ?, ?)
  `);

  const insertSource = db.prepare(`
    INSERT INTO scholarship_sources (
      scholarship_id, source_name, source_url, source_type, publication_date, evidence_excerpt, verification_result
    ) VALUES (?, ?, ?, ?, '2026-08-01', ?, 'VERIFIED')
  `);

  for (const s of SEED_SCHOLARSHIPS) {
    try {
      insertScholarship.run(
        s.slug, s.title, s.title, s.provider, s.amount_display, s.who_can_apply, s.application_close_at, s.category, s.subcategory, s.academic_year,
        s.description, s.benefits_summary, s.amount_min, s.amount_max, s.amount_display,
        s.education_level, s.eligible_branches, s.eligible_years, s.min_percentage, s.max_income,
        s.applicable_states, s.outside_state_study_allowed, s.gender_restriction,
        s.category_restriction, s.defence_category, s.application_type,
        s.application_open_at, s.application_close_at, s.institute_verification_deadline,
        s.official_application_url, s.official_application_url, s.official_scheme_url, s.official_guideline_url,
        s.who_can_apply, s.who_cannot_apply, s.required_documents, s.application_procedure,
        s.status, s.verification_status, s.is_featured
      );

      const created = db.prepare("SELECT id FROM scholarships WHERE slug = ?").get(s.slug);
      if (created) {
        // Clear previous rules & sources for clean idempotent seed
        db.prepare("DELETE FROM scholarship_eligibility_rules WHERE scholarship_id = ?").run(created.id);
        db.prepare("DELETE FROM scholarship_sources WHERE scholarship_id = ?").run(created.id);

        if (Array.isArray(s.rules)) {
          for (const r of s.rules) {
            insertRule.run(created.id, r.criterion_type, r.operator, r.criterion_value, r.is_mandatory, r.explanation, s.provider);
          }
        }

        if (Array.isArray(s.sources)) {
          for (const src of s.sources) {
            insertSource.run(created.id, src.source_name, src.source_url, src.source_type, src.evidence_excerpt);
          }
        }
      }
    } catch (e) {
      console.warn(`Note during scholarship seed (${s.slug}):`, e.message);
    }
  }

  console.log(`✓ Seeded ${SEED_SCHOLARSHIPS.length} verified authentic scholarships into database.`);
}
