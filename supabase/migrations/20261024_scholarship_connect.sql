  category TEXT DEFAULT 'GENERAL',
  gender TEXT DEFAULT 'MALE',
  is_differently_abled SMALLINT DEFAULT 0,
  disability_percentage INT DEFAULT 0,
  twelfth_percentage NUMERIC(5,2),
  cgpa NUMERIC(4,2),
  admission_year INT,
