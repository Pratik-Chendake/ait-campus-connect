  who_cannot_apply TEXT,
  application_procedure TEXT,
  status TEXT DEFAULT 'OPEN',
  verification_status TEXT DEFAULT 'VERIFIED',
  last_verified_at TIMESTAMPTZ DEFAULT NOW(),
  is_featured SMALLINT DEFAULT 0,
  is_active SMALLINT DEFAULT 1,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Indexes for performance
CREATE INDEX IF NOT EXISTS idx_scholarships_category ON public.scholarships(category);
CREATE INDEX IF NOT EXISTS idx_scholarships_status ON public.scholarships(status);
CREATE INDEX IF NOT EXISTS idx_scholarships_deadline ON public.scholarships(application_close_at);
CREATE INDEX IF NOT EXISTS idx_scholarships_verification ON public.scholarships(verification_status);

-- 2. Scholarship Rules
CREATE TABLE IF NOT EXISTS public.scholarship_eligibility_rules (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  scholarship_id BIGINT REFERENCES public.scholarships(id) ON DELETE CASCADE,
  criterion_type TEXT NOT NULL,
  operator TEXT NOT NULL,
  criterion_value TEXT NOT NULL,
  is_mandatory SMALLINT DEFAULT 1,
  explanation TEXT,
  source_reference TEXT
);

